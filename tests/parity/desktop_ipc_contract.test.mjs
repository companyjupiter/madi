import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import test from 'node:test';

const root = resolve(import.meta.dirname, '../..');
const read = path => readFileSync(resolve(root, path), 'utf8');

test('every desktop command has a generated permission and an intended window grant', () => {
  const handler = read('apps/desktop/src-tauri/src/main.rs').match(/tauri::generate_handler!\[([^\]]+)\]/);
  assert.ok(handler, 'Native command registry must be found');
  const registered = handler[1].split(',').map(value => value.trim()).filter(Boolean);
  const manifest = read('apps/desktop/src-tauri/build.rs').match(/\.commands\(&\[([^\]]+)\]/);
  assert.ok(manifest, 'Tauri build-time command manifest must be found');
  const declared = [...manifest[1].matchAll(/"([a-z_]+)"/g)].map(match => match[1]);
  assert.deepEqual(declared.toSorted(), registered.toSorted(), 'A handler alone does not make a command callable: keep the permission manifest complete');
  const capability = JSON.parse(read('apps/desktop/src-tauri/capabilities/main.json'));
  assert.deepEqual(capability.windows, ['main']);
  assert.equal(capability.remote, undefined, 'Local commands are not granted to remote pages');
  const captionOnly = ['caption_snapshot', 'caption_close', 'caption_resize'];
  const staff = JSON.parse(read('apps/desktop/src-tauri/capabilities/caption-staff.json'));
  for (const command of registered) {
    const permission = `allow-${command.replaceAll('_', '-')}`;
    assert.equal(capability.permissions.includes(permission), !captionOnly.includes(command), `Incorrect main-window permission: ${command}`);
    if (captionOnly.includes(command)) assert.ok(staff.permissions.includes(permission), `Missing caption permission: ${command}`);
    const generated = read(`apps/desktop/src-tauri/permissions/autogenerated/${command}.toml`);
    assert.ok(generated.includes(`commands.allow = ["${command}"]`), `Generated command permission missing: ${command}`);
  }
  for (const path of readdirSync(resolve(root, 'apps/desktop/src'), {recursive: true})) {
    if (!/\.tsx?$/.test(path)) continue;
    for (const match of read(`apps/desktop/src/${path}`).matchAll(/\binvoke(?:<[^;()]*>)?\(\s*['"]([a-z_]+)['"]/g)) {
      assert.ok(registered.includes(match[1]), `Renderer invokes an unregistered command: ${match[1]} in ${path}`);
    }
  }
});

test('caption windows receive only projections, own resizing and staff-only close', () => {
  const config = JSON.parse(read('apps/desktop/src-tauri/tauri.conf.json'));
  for (const audience of ['staff', 'patient']) {
    const id = `caption-${audience}`;
    const capability = JSON.parse(read(`apps/desktop/src-tauri/capabilities/${id}.json`));
    assert.deepEqual(capability.windows, [id]);
    assert.equal(capability.remote, undefined);
    assert.deepEqual(capability.permissions.toSorted(), [
      'allow-caption-snapshot', 'allow-caption-resize',
      ...(audience === 'staff' ? ['allow-caption-close'] : []),
      'core:event:allow-listen', 'core:event:allow-unlisten', 'core:window:allow-start-dragging',
    ].toSorted());
    assert.ok(config.app.security.capabilities.includes(id));
  }
});

test('Settings gets only its own local capabilities and cannot admit or edit files', () => {
  const capability = JSON.parse(read('apps/desktop/src-tauri/capabilities/settings.json'));
  assert.deepEqual(capability.windows, ['settings']);
  assert.equal(capability.remote, undefined);
  const commands = [
    'settings_open', 'settings_metadata', 'settings_model_locations', 'settings_models_command', 'settings_reveal',
    'preferences_snapshot', 'preferences_command', 'settings_command', 'glossary_snapshot', 'glossary_command',
    'setup_command', 'audio_inputs', 'models_snapshot', 'workspace_snapshot', 'workspace_command', 'workspace_choose_folder',
  ];
  assert.deepEqual(capability.permissions.toSorted(), [
    ...commands.map(command => `allow-${command.replaceAll('_', '-')}`),
    'core:event:allow-listen', 'core:event:allow-unlisten', 'core:window:allow-set-title',
  ].toSorted());
  const config = JSON.parse(read('apps/desktop/src-tauri/tauri.conf.json'));
  const settings = config.app.windows.find(window => window.label === 'settings');
  assert.equal(settings.url, 'index.html#settings');
  assert.equal(settings.visible, false);
  assert.ok(config.app.security.capabilities.includes('settings'));
  // This window can only change the two shared setup bindings. Staging/file
  // selection and all session admission/edit commands remain main-only.
  const main = read('apps/desktop/src-tauri/src/main.rs');
  const setup = main.slice(main.indexOf('async fn setup_command('), main.indexOf('fn audio_inputs('));
  assert.match(setup, /window.label\(\) == "settings"/);
  assert.match(setup, /SetupCommand::AudioSource\(_\) \| SetupCommand::Diarize\(_\)/);
  assert.ok(setup.indexOf('unsupported settings setup intent') < setup.indexOf('.setup(command)'));
});
