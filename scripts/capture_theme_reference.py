#!/usr/bin/env python3
"""Capture actual AppKit-resolved Theme.swift colors and generate the CSS reference."""
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out/theme-parity"
SOURCE = ROOT / "apps/macos/Sovereign/UI/Theme.swift"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    subprocess.run(["swiftc", str(SOURCE), str(ROOT / "tests/parity/ThemeOracle.swift"),
                    "-o", str(OUT / "theme-oracle")], check=True)
    data = json.loads(subprocess.check_output([str(OUT / "theme-oracle")]))
    data["sourceSHA256"] = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    data["source"] = str(SOURCE.relative_to(ROOT))
    data["status"] = "native-color-reference-only"
    target = ROOT / "design/parity/theme-reference.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    blocks = []
    # :root also matches a dark root; emit the explicit dark override last.
    for mode in ("light", "dark"):
        colors = data["appearances"][mode]
        declarations = [f"  --{key}: rgb({r*255:.4f} {g*255:.4f} {b*255:.4f} / {a:.6f});"
                        for key, (r, g, b, a) in sorted(colors.items())]
        selector = ":root, [data-theme=light]" if mode == "light" else "[data-theme=dark]"
        blocks.append(selector + " {\n" + "\n".join(declarations) + "\n}")
    css = ROOT / "apps/desktop/src/theme.generated.css"
    css.parent.mkdir(parents=True, exist_ok=True)
    css.write_text("/* Generated by scripts/capture_theme_reference.py from shipping Theme.swift.\n"
                   "   OS-specific color reference; visual parity remains unverified. */\n"
                   + "\n".join(blocks) + "\n")
    print(f"Captured {len(data['appearances']['light'])} tokens in both appearances: {target}")


if __name__ == "__main__":
    main()
